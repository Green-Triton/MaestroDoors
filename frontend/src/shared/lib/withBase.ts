/**
 * Приводит абсолютный путь к статике с учётом базового пути сборки.
 *
 * Сборка может публиковаться не в корень домена (например, GitHub Pages отдаёт
 * сайт по адресу `/<repo>/`). Vite подставляет базовый путь только в те ссылки,
 * которые видит на этапе сборки, — а пути из сгенерированного датасета это
 * обычные строки, и без нормализации они уедут в корень домена и вернут 404.
 */
const BASE = import.meta.env.BASE_URL

export const withBase = (path: string): string => {
  if (!path) return path
  // Внешние адреса и data-URI трогать нельзя.
  if (/^([a-z]+:)?\/\//i.test(path) || path.startsWith('data:')) return path
  return `${BASE.replace(/\/$/, '')}/${path.replace(/^\//, '')}`
}
